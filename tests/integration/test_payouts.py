async def entries_of(
    engine: AsyncEngine, payout_id: str
) -> list[tuple[str, list[tuple[str, int]]]]:
    """(entry_type, [(account kind or 'customer:<id>', amount)]) of the payout's entries."""
    async with engine.connect() as c:
        rows = (
            await c.execute(
                text(
                    """
                    SELECT e.id, e.entry_type, COALESCE(a.system_kind, 'customer:' || a.id) AS who,
                           l.amount_minor
                    FROM journal_entries e JOIN entry_lines l ON l.entry_id = e.id
                    JOIN accounts a ON a.id = l.account_id
                    WHERE e.description LIKE :p ORDER BY e.id, l.id
                    """
                ),
                {"p": f"payout:{payout_id}%"},
            )
        ).all()
    out: dict[int, tuple[str, list[tuple[str, int]]]] = {}
    for r in rows:
        out.setdefault(r.id, (r.entry_type, []))[1].append((r.who, r.amount_minor))
    return list(out.values())


async def balance_of(engine: AsyncEngine, account_id: int) -> int:
    async with engine.connect() as c:
        return int(
            (
                await c.execute(
                    text("SELECT balance_minor FROM balances WHERE account_id = :a"),
                    {"a": account_id},
                )
            ).scalar_one()
        )


async def system_balance(engine: AsyncEngine, kind: str) -> int:
    async with engine.connect() as c:
        return int(
            (
                await c.execute(
                    text(
                        "SELECT COALESCE(sum(b.balance_minor), 0) FROM balances b "
                        "JOIN accounts a ON a.id = b.account_id WHERE a.system_kind = :k"
                    ),
                    {"k": kind},
                )
            ).scalar_one()
        )


async def events_of(engine: AsyncEngine, payout_id: str) -> list[str]:
    async with engine.connect() as c:
        rows = await c.execute(
            text(
                "SELECT event_type FROM outbox_events "
                "WHERE aggregate_type = 'payout' AND aggregate_id = :i ORDER BY seq"
            ),
            {"i": payout_id},
        )
        return [r[0] for r in rows]


async def assert_ledger_ok(engine: AsyncEngine, sm: SM) -> None:
    """Money invariants that must hold after ANY sequence of saga steps and crashes."""
    async with engine.connect() as c:
        assert (
            await c.execute(text("SELECT COALESCE(sum(balance_minor), 0) FROM balances"))
        ).scalar_one() == 0
        assert (
            await c.execute(text("SELECT COALESCE(sum(amount_minor), 0) FROM entry_lines"))
        ).scalar_one() == 0
        # Holds account == exactly the payouts whose funds are still held.
        held = (
            await c.execute(
                text("SELECT COALESCE(sum(amount_minor), 0) FROM payouts WHERE status = ANY(:s)"),
                {"s": [s.value for s in LIVE]},
            )
        ).scalar_one()
        # A payout row is committed only together with its hold; completed money sits in
        # clearing, released money is back with the customer.
        clearing = (
            await c.execute(
                text(
                    "SELECT COALESCE(sum(amount_minor), 0) FROM payouts WHERE status = 'COMPLETED'"
                )
            )
        ).scalar_one()
        # Exactly one HOLD_RELEASE/PAYOUT per payout at most; one HOLD per non-rejected one.
        dup = (
            await c.execute(
                text(
                    "SELECT count(*) FROM (SELECT description, entry_type FROM journal_entries "
                    "WHERE entry_type IN ('HOLD', 'HOLD_RELEASE', 'PAYOUT') "
                    "GROUP BY description, entry_type HAVING count(*) > 1) d"
                )
            )
        ).scalar_one()
    assert dup == 0
    assert await system_balance(engine, "holds") == held
    assert await system_balance(engine, "clearing") == clearing
    async with sm() as s, s.begin():
        assert await find_drift(s) == []


