class ScriptedProvider(FakePayoutProvider):
    """FakePayoutProvider whose *next unseen payout id* gets ``next_behavior``.

    Payout ids are generated by the service, so tests cannot script them in advance.
    """

    def __init__(self, next_behavior: FakeBehavior | None = None) -> None:
        super().__init__()
        self.next_behavior = next_behavior

    async def submit(self, payout_id: str, amount: Money, destination: str) -> ProviderResult:
        if payout_id not in self.behaviors and self.next_behavior is not None:
            self.script(payout_id, self.next_behavior)
        return await super().submit(payout_id, amount, destination)


class Boom(RuntimeError):
    pass


def crash_at(point: str) -> Any:
    """A fault hook that raises Boom the first time ``point`` is reached."""
    fired = {"done": False}

    def fault(name: str) -> None:
        if name == point and not fired["done"]:
            fired["done"] = True
            raise Boom(point)

    return fault


