async def test_db_guard_matches_domain_transition_table(sessionmaker: SM) -> None:
    acct = await make_account(sessionmaker, funded=10)
    async with sessionmaker() as s, s.begin():
        for src, dst in itertools.permutations(list(S), 2):
            pid = str(uuid.uuid4())
            await s.execute(
                text(
                    "INSERT INTO payouts (id, account_id, amount_minor, currency, destination, "
                    "status) VALUES (:i, :a, 1, 'USD', 'd', :s)"
                ),
                {"i": pid, "a": acct, "s": src.value},
            )
            try:
                async with s.begin_nested():
                    await s.execute(
                        text("UPDATE payouts SET status = :d WHERE id = :i"),
                        {"d": dst.value, "i": pid},
                    )
                allowed = True
            except DBAPIError:
                allowed = False
            assert allowed == can_transition(src, dst), (src, dst)
    assert all(not can_transition(t, d) for t in TERMINAL for d in S)


