async def test_happy_path_ledger_balances_events(engine: AsyncEngine, sessionmaker: SM) -> None:
    acct = await make_account(sessionmaker, funded=10_000)
    provider = ScriptedProvider()
    p = await new_payout(sessionmaker, acct)
    assert p.status is S.HELD and p.hold_entry_id is not None
    assert await balance_of(engine, acct) == 10_000 - AMOUNT  # funds reserved at once

    done = await saga_for(sessionmaker, provider).advance(p.id)

    assert done.status is S.COMPLETED and done.final_entry_id is not None
    assert done.provider_reference == f"fake-{p.id}"
    assert await entries_of(engine, p.id) == [
        ("HOLD", [(f"customer:{acct}", -AMOUNT), ("holds", AMOUNT)]),
        ("PAYOUT", [("holds", -AMOUNT), ("clearing", AMOUNT)]),
    ]
    assert await balance_of(engine, acct) == 10_000 - AMOUNT
    assert await system_balance(engine, "holds") == 0
    assert await system_balance(engine, "clearing") == AMOUNT
    assert await events_of(engine, p.id) == ["payout.held", "payout.completed"]
    assert len(provider.money_sent) == 1
    await assert_ledger_ok(engine, sessionmaker)


