def body(acct: int, amount: int = AMOUNT, **over: Any) -> dict[str, Any]:
    return {
        "account_id": acct,
        "amount_minor": amount,
        "currency": "USD",
        "destination": "acct-123",
    } | over


async def post_payout(c: AsyncClient, b: dict[str, Any], k: str | None = None) -> Response:
    return await c.post("/payouts", json=b, headers={"Idempotency-Key": k or str(uuid.uuid4())})


def problem(r: Response, status: int, code: str) -> None:
    assert r.status_code == status, r.text
    assert r.headers["content-type"].startswith("application/problem+json")
    assert r.json()["code"] == code


async def test_api_create_get_and_replay(
    client: AsyncClient, engine: AsyncEngine, sessionmaker: SM, provider: ScriptedProvider
) -> None:
    acct = await make_account(sessionmaker, funded=10_000)
    k = str(uuid.uuid4())
    r = await post_payout(client, body(acct), k)
    assert r.status_code == 201 and r.headers["Idempotent-Replayed"] == "false"
    out = r.json()
    assert out["status"] == "COMPLETED" and out["hold_entry_id"] and out["final_entry_id"]

    again = await post_payout(client, body(acct), k)
    assert again.status_code == 201 and again.headers["Idempotent-Replayed"] == "true"
    assert again.json()["id"] == out["id"]
    assert len(provider.submit_calls) == 1 and len(provider.money_sent) == 1

    problem(await post_payout(client, body(acct, 1), k), 422, "idempotency_key_reuse")
    got = await client.get(f"/payouts/{out['id']}")
    assert got.status_code == 200 and got.json()["status"] == "COMPLETED"
    await assert_ledger_ok(engine, sessionmaker)


