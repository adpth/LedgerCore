@pytest.mark.parametrize(
    ("point", "behavior"),
    [
        ("after_hold", None),
        ("after_provider_pending", None),
        ("after_provider_call", None),
        ("in_apply_tx", None),
        ("after_provider_call", FakeBehavior.FAIL),
        ("after_failed", FakeBehavior.FAIL),
        ("after_provider_call", FakeBehavior.TIMEOUT_AFTER_SUCCESS),
    ],
)
async def test_crash_at_each_boundary_recovers(
    engine: AsyncEngine, sessionmaker: SM, point: str, behavior: FakeBehavior | None
) -> None:
    acct = await make_account(sessionmaker, funded=10_000)
    provider = ScriptedProvider(behavior)
    p = await new_payout(sessionmaker, acct)

    with pytest.raises(Boom):
        await saga_for(sessionmaker, provider, crash_at(point)).advance(p.id)
    crashed = await saga_for(sessionmaker, provider).get(p.id)
    assert not crashed.is_terminal  # the crash really did interrupt the saga
    if point == "in_apply_tx":  # ledger entry and status change roll back together
        assert crashed.status is S.PROVIDER_PENDING
        assert [t for t, _ in await entries_of(engine, p.id)] == ["HOLD"]
    await assert_ledger_ok(engine, sessionmaker)

    report = await run_once(sessionmaker, provider, stale_after_s=0)
    assert report.errors == 0

    final = await saga_for(sessionmaker, provider).get(p.id)
    if behavior is FakeBehavior.FAIL:
        assert final.status is S.RELEASED
        assert provider.money_sent == [] and await balance_of(engine, acct) == 10_000
    else:
        assert final.status is S.COMPLETED
        assert len(provider.money_sent) == 1 and await balance_of(engine, acct) == 7_500
    assert len(provider.money_sent) <= 1
    await assert_ledger_ok(engine, sessionmaker)
    again = await run_once(sessionmaker, provider, stale_after_s=0)
    assert again.examined == 0  # nothing left to do


