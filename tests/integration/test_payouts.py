async def test_recovery_of_pending_rows(engine: AsyncEngine, sessionmaker: SM) -> None:
    """A committed PENDING payout (hold posted or not) is finished without a double hold."""
    from ledgercore.db.posting import LineInput, post_entry
    from ledgercore.services.ledger import get_or_create_system_account

    acct = await make_account(sessionmaker, funded=10_000)
    ids = {"with_hold": str(uuid.uuid4()), "no_hold": str(uuid.uuid4())}
    async with sessionmaker() as s, s.begin():
        for pid in ids.values():
            await s.execute(
                text(
                    "INSERT INTO payouts (id, account_id, amount_minor, currency, destination, "
                    "status) VALUES (:i, :a, :m, 'USD', 'd', 'PENDING')"
                ),
                {"i": pid, "a": acct, "m": AMOUNT},
            )
        holds = await get_or_create_system_account(s, "USD", "holds")
        await post_entry(
            s,
            "HOLD",
            [LineInput(acct, -AMOUNT, "USD"), LineInput(holds, AMOUNT, "USD")],
            description=f"payout:{ids['with_hold']}:hold",
        )
    provider = ScriptedProvider()
    report = await run_once(sessionmaker, provider, stale_after_s=0)
    assert report.examined == 2 and report.errors == 0
    saga = saga_for(sessionmaker, provider)
    for pid in ids.values():
        assert (await saga.get(pid)).status is S.COMPLETED
        assert [t for t, _ in await entries_of(engine, pid)] == ["HOLD", "PAYOUT"]
    assert await balance_of(engine, acct) == 10_000 - 2 * AMOUNT
    await assert_ledger_ok(engine, sessionmaker)


async def test_concurrent_recovery_workers_do_not_double_post(
    engine: AsyncEngine, sessionmaker: SM
) -> None:
    acct = await make_account(sessionmaker, funded=100_000)
    provider = ScriptedProvider()
    stuck_pending: list[str] = []
    stuck_failed: list[str] = []
    for i in range(10):
        p = await new_payout(sessionmaker, acct, 100)
        point = "after_provider_pending" if i % 2 == 0 else "after_failed"
        if point == "after_failed":
            provider.script(p.id, FakeBehavior.FAIL)
        with pytest.raises(Boom):
            await saga_for(sessionmaker, provider, crash_at(point)).advance(p.id)
        (stuck_pending if i % 2 == 0 else stuck_failed).append(p.id)

    reports = await asyncio.gather(
        *(run_once(sessionmaker, provider, stale_after_s=0) for _ in range(8))
    )

    assert sum(r.errors for r in reports) == 0
    saga = saga_for(sessionmaker, provider)
    for pid in stuck_pending:
        assert (await saga.get(pid)).status is S.COMPLETED
        assert [t for t, _ in await entries_of(engine, pid)] == ["HOLD", "PAYOUT"]
    for pid in stuck_failed:
        assert (await saga.get(pid)).status is S.RELEASED
        assert [t for t, _ in await entries_of(engine, pid)] == ["HOLD", "HOLD_RELEASE"]
    paid = [m.payout_id for m in provider.money_sent]
    assert sorted(paid) == sorted(stuck_pending)  # each paid exactly once
    assert await balance_of(engine, acct) == 100_000 - 5 * 100
    await assert_ledger_ok(engine, sessionmaker)


async def test_provider_is_never_called_while_a_row_lock_is_held(
    engine: AsyncEngine, sessionmaker: SM
) -> None:
    class LockProbe(ScriptedProvider):
        lock_seen: list[bool]
        idle_seen: list[int]

        def __init__(self) -> None:
            super().__init__()
            self.lock_seen, self.idle_seen = [], []

        async def submit(self, payout_id: str, amount: Money, destination: str) -> ProviderResult:
            # If the saga held the payout row lock, this FOR UPDATE NOWAIT would fail.
            try:
                async with sessionmaker() as s, s.begin():
                    await s.execute(
                        text("SELECT 1 FROM payouts WHERE id = :i FOR UPDATE NOWAIT"),
                        {"i": payout_id},
                    )
                self.lock_seen.append(False)
            except DBAPIError:
                self.lock_seen.append(True)
            async with engine.connect() as c:  # and no transaction of ours is idle-open on it
                n = (
                    await c.execute(
                        text(
                            "SELECT count(*) FROM pg_stat_activity "
                            "WHERE state = 'idle in transaction' AND datname = current_database()"
                        )
                    )
                ).scalar_one()
            self.idle_seen.append(int(n))
            return await super().submit(payout_id, amount, destination)

    acct = await make_account(sessionmaker, funded=10_000)
    provider = LockProbe()
    p = await new_payout(sessionmaker, acct)
    await saga_for(sessionmaker, provider).advance(p.id)
    assert provider.lock_seen == [False]  # row lock free during the call
    assert provider.idle_seen == [0]  # no transaction open (idle in transaction)


