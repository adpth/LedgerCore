async def test_api_generic_reversal_of_saga_entries_is_rejected(
    client: AsyncClient, engine: AsyncEngine, sessionmaker: SM, provider: ScriptedProvider
) -> None:
    acct = await make_account(sessionmaker, funded=10_000)
    provider.next_behavior = FakeBehavior.FAIL
    failed = (await post_payout(client, body(acct))).json()
    assert failed["status"] == "RELEASED"
    provider.next_behavior = None
    paid = (await post_payout(client, body(acct))).json()
    assert paid["status"] == "COMPLETED"

    for entry_id, etype in (
        (failed["hold_entry_id"], "HOLD"),
        (failed["release_entry_id"], "HOLD_RELEASE"),
        (paid["final_entry_id"], "PAYOUT"),
    ):
        r = await client.post(
            f"/entries/{entry_id}/reverse", headers={"Idempotency-Key": str(uuid.uuid4())}
        )
        problem(r, 422, "entry_not_reversible")
        assert r.json()["entry_type"] == etype
    async with engine.connect() as c:  # nobody stole the reverses_entry_id slot
        assert (
            await c.execute(
                text("SELECT count(*) FROM journal_entries WHERE entry_type='REVERSAL'")
            )
        ).scalar_one() == 0
    await assert_ledger_ok(engine, sessionmaker)
